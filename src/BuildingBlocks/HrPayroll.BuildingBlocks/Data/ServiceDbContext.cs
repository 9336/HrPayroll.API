using System.Text.Json;
using HrPayroll.BuildingBlocks.Directory;
using HrPayroll.BuildingBlocks.Messaging;
using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Infrastructure;
using Microsoft.Extensions.DependencyInjection;

namespace HrPayroll.BuildingBlocks.Data;

/// <summary>How a service holds the company directory tables.</summary>
/// <param name="OwnsEmployees">Employees service: the source of employees, departments, holidays and the company master.</param>
/// <param name="OwnsUsers">Identity service: the source of logins and roles (with password hashes).</param>
/// <param name="IncludeFinancialDetails">The copy keeps PAN and bank details (Payroll only).</param>
public sealed record DirectoryModel(bool OwnsEmployees = false, bool OwnsUsers = false, bool IncludeFinancialDetails = false);

/// <summary>A change to publish: topic, message key and event.</summary>
public sealed record OutboxEvent(string Topic, string Key, object Payload);

/// <summary>
/// Base of every service's database context: the outbox / inbox tables and the company directory (owned or copied).
/// Services that own records other services copy override <see cref="Publishes"/> and <see cref="EventsAfterSaveAsync"/>:
/// the events are written to the outbox in the same transaction as the change.
/// </summary>
public abstract class ServiceDbContext(DbContextOptions options) : DbContext(options)
{
    public DbSet<OutboxMessage> OutboxMessages => Set<OutboxMessage>();
    public DbSet<InboxMessage> InboxMessages => Set<InboxMessage>();

    public DbSet<Role> Roles => Set<Role>();
    public DbSet<RolePermission> RolePermissions => Set<RolePermission>();
    public DbSet<User> Users => Set<User>();
    public DbSet<Department> Departments => Set<Department>();
    public DbSet<Employee> Employees => Set<Employee>();
    public DbSet<Holiday> Holidays => Set<Holiday>();
    public DbSet<CompanyProfile> CompanyProfiles => Set<CompanyProfile>();

    /// <summary>Must be the same for every instance of the context type (EF caches the model per type).</summary>
    protected abstract DirectoryModel Directory { get; }

    /// <summary>The service's own tables.</summary>
    protected abstract void ConfigureModel(ModelBuilder b);

    protected sealed override void OnModelCreating(ModelBuilder b)
    {
        MessagingModel.Map(b);
        DirectoryModelBuilder.Map(b, Directory);
        ConfigureModel(b);
    }

    // ------------------------------------------------------------------ Publishing
    /// <summary>Adds an event to the outbox; it is saved with the next SaveChanges and then sent to Kafka.</summary>
    public void Publish(string topic, string key, object payload) =>
        OutboxMessages.Add(new OutboxMessage
        {
            MessageId = Guid.NewGuid(),
            Topic = topic,
            MessageKey = key,
            EventType = payload.GetType().Name,
            Payload = JsonSerializer.Serialize(payload, payload.GetType(), EventJson.Options),
            OccurredAt = DateTime.UtcNow,
        });

    /// <summary>Entity types whose changes produce integration events.</summary>
    protected virtual bool Publishes(Type entityType) => false;

    /// <summary>Events for the changes just saved (keys generated by the database are available here).</summary>
    protected virtual Task<IEnumerable<OutboxEvent>> EventsAfterSaveAsync(IReadOnlyList<(object Entity, EntityState State)> changes, CancellationToken ct) =>
        Task.FromResult<IEnumerable<OutboxEvent>>([]);

    public override int SaveChanges(bool acceptAllChangesOnSuccess) =>
        SaveChangesAsync(acceptAllChangesOnSuccess).GetAwaiter().GetResult();

    public override async Task<int> SaveChangesAsync(bool acceptAllChangesOnSuccess, CancellationToken ct = default)
    {
        var changes = ChangeTracker.Entries()
            .Where(e => e.State is EntityState.Added or EntityState.Modified or EntityState.Deleted && Publishes(e.Entity.GetType()))
            .Select(e => (e.Entity, e.State))
            .ToList();
        var outboxWritten = changes.Count > 0 || ChangeTracker.Entries<OutboxMessage>().Any(e => e.State == EntityState.Added);

        int result;
        if (changes.Count == 0)
            result = await base.SaveChangesAsync(acceptAllChangesOnSuccess, ct);
        else if (Database.CurrentTransaction is not null)
            result = await SaveWithEventsAsync(changes, acceptAllChangesOnSuccess, ct);
        else
        {
            await using var tx = await Database.BeginTransactionAsync(ct);
            result = await SaveWithEventsAsync(changes, acceptAllChangesOnSuccess, ct);
            await tx.CommitAsync(ct);
        }

        if (outboxWritten) Signal?.Notify();
        return result;
    }

    private async Task<int> SaveWithEventsAsync(List<(object Entity, EntityState State)> changes, bool accept, CancellationToken ct)
    {
        var result = await base.SaveChangesAsync(accept, ct);
        var events = (await EventsAfterSaveAsync(changes, ct))
            .GroupBy(e => (e.Topic, e.Key, Type: e.Payload.GetType()))
            .Select(g => g.Last())   // several changes to one record in one save: publish its final state once
            .ToList();
        if (events.Count == 0) return result;
        foreach (var e in events) Publish(e.Topic, e.Key, e.Payload);
        await base.SaveChangesAsync(accept, ct);
        return result;
    }

    private OutboxSignal? Signal =>
        this.GetService<IDbContextOptions>().FindExtension<CoreOptionsExtension>()?.ApplicationServiceProvider?.GetService<OutboxSignal>();
}
