/* ---------------------------------------------------------------------
   Tables owned by the Notifications service
   --------------------------------------------------------------------- */
IF OBJECT_ID('dbo.EmailMessages', 'U') IS NULL
BEGIN
    CREATE TABLE dbo.EmailMessages
    (
        EmailId    BIGINT IDENTITY(1,1) NOT NULL CONSTRAINT PK_EmailMessages PRIMARY KEY,
        ToAddress  NVARCHAR(200)        NOT NULL,
        ToName     NVARCHAR(200)        NULL,
        Subject    NVARCHAR(200)        NOT NULL,
        HtmlBody   NVARCHAR(MAX)        NOT NULL,
        Category   NVARCHAR(50)         NOT NULL CONSTRAINT DF_EmailMessages_Category DEFAULT ('General'),
        Status     NVARCHAR(20)         NOT NULL CONSTRAINT DF_EmailMessages_Status DEFAULT ('Pending'),
        NotBefore  DATETIME2(0)         NOT NULL,   -- office local time
        Attempts   INT                  NOT NULL CONSTRAINT DF_EmailMessages_Attempts DEFAULT (0),
        LastError  NVARCHAR(500)        NULL,
        CreatedAt  DATETIME2(0)         NOT NULL CONSTRAINT DF_EmailMessages_CreatedAt DEFAULT (SYSUTCDATETIME()),
        SentAt     DATETIME2(0)         NULL,
        CONSTRAINT CK_EmailMessages_Status CHECK (Status IN ('Pending','Sent','Failed','Logged','Skipped'))
    );
    CREATE INDEX IX_EmailMessages_Queue ON dbo.EmailMessages(Status, NotBefore);
END
GO
/* ---------------------------------------------------------------------
   3l. OUTGOING MAIL (SMTP) SETTINGS
