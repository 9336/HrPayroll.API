    CREATE TABLE dbo.EmailSettings
    (
        SettingsId        INT            NOT NULL CONSTRAINT PK_EmailSettings PRIMARY KEY
                                         CONSTRAINT CK_EmailSettings_Single CHECK (SettingsId = 1),   -- one row
        IsEnabled         BIT            NOT NULL CONSTRAINT DF_EmailSettings_Enabled DEFAULT (0),
        Host              NVARCHAR(200)  NULL,
        Port              INT            NOT NULL CONSTRAINT CK_EmailSettings_Port CHECK (Port BETWEEN 1 AND 65535),
        Security          VARCHAR(20)    NOT NULL CONSTRAINT CK_EmailSettings_Security CHECK (Security IN ('StartTls','SslOnConnect','Auto','None')),
        Username          NVARCHAR(200)  NULL,
        PasswordProtected NVARCHAR(MAX)  NULL,   -- encrypted by the API (ASP.NET Core Data Protection), never plain text
        FromAddress       NVARCHAR(200)  NOT NULL,
        FromName          NVARCHAR(100)  NOT NULL,
        DisabledCategories NVARCHAR(500) NULL,   -- kinds of email switched off (comma-separated)
        UpdatedAt         DATETIME2(0)   NULL,   -- UTC
        UpdatedByUserId   INT            NULL
    );
