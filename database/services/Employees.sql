   3e. ID CARD PHOTO, ATTENDANCE, WORK LOG
   --------------------------------------------------------------------- */
-- Separate table so loading an employee never loads the photo bytes.
CREATE TABLE dbo.EmployeePhotos
(
    EmployeeId  INT            NOT NULL CONSTRAINT PK_EmployeePhotos PRIMARY KEY
                               CONSTRAINT FK_EmployeePhotos_Employees REFERENCES dbo.Employees(EmployeeId) ON DELETE CASCADE,
    Photo       VARBINARY(MAX) NOT NULL,
    ContentType NVARCHAR(50)   NOT NULL,
    UpdatedAt   DATETIME2(0)   NOT NULL
);
GO
-- Documents employees upload themselves (ID proofs, certificates…) and HR verifies.
CREATE TABLE dbo.EmployeeUploads
(
    UploadId         INT IDENTITY(1,1) NOT NULL CONSTRAINT PK_EmployeeUploads PRIMARY KEY,
    EmployeeId       INT            NOT NULL CONSTRAINT FK_EmployeeUploads_Employees REFERENCES dbo.Employees(EmployeeId),
    Category         NVARCHAR(60)   NOT NULL,
    Title            NVARCHAR(150)  NOT NULL,
    FileName         NVARCHAR(200)  NOT NULL,
    ContentType      VARCHAR(100)   NOT NULL,
    SizeBytes        INT            NOT NULL,
    Status           NVARCHAR(20)   NOT NULL CONSTRAINT DF_EmployeeUploads_Status DEFAULT (N'Pending')
                     CONSTRAINT CK_EmployeeUploads_Status CHECK (Status IN (N'Pending', N'Verified', N'Rejected')),
    UploadedAt       DATETIME2(0)   NOT NULL,
    ReviewedByUserId INT            NULL,
    ReviewedAt       DATETIME2(0)   NULL,
    ReviewNote       NVARCHAR(500)  NULL
);
CREATE INDEX IX_EmployeeUploads_Employee ON dbo.EmployeeUploads (EmployeeId, UploadedAt DESC);
CREATE INDEX IX_EmployeeUploads_Status ON dbo.EmployeeUploads (Status) INCLUDE (EmployeeId);
GO
CREATE TABLE dbo.EmployeeUploadFiles
(
    UploadId INT            NOT NULL CONSTRAINT PK_EmployeeUploadFiles PRIMARY KEY
                            CONSTRAINT FK_EmployeeUploadFiles_Uploads REFERENCES dbo.EmployeeUploads(UploadId) ON DELETE CASCADE,
    Data     VARBINARY(MAX) NOT NULL
);
GO
