CREATE TABLE dbo.Employees
(
    EmployeeId     INT IDENTITY(1,1) NOT NULL CONSTRAINT PK_Employees PRIMARY KEY,
    EmployeeCode   NVARCHAR(20)      NOT NULL CONSTRAINT UQ_Employees_Code UNIQUE,
    FirstName      NVARCHAR(100)     NOT NULL,
    LastName       NVARCHAR(100)     NOT NULL,
    Email          NVARCHAR(200)     NOT NULL CONSTRAINT UQ_Employees_Email UNIQUE,
    Phone          NVARCHAR(20)      NULL,
    Gender         CHAR(1)           NULL CONSTRAINT CK_Employees_Gender CHECK (Gender IN ('M','F','O')),
    DateOfBirth    DATE              NULL,
    DateOfJoining  DATE              NOT NULL,
    DepartmentId   INT               NOT NULL CONSTRAINT FK_Employees_Departments REFERENCES dbo.Departments(DepartmentId),
    Designation    NVARCHAR(100)     NOT NULL,
    ManagerId      INT               NULL     CONSTRAINT FK_Employees_Manager REFERENCES dbo.Employees(EmployeeId), -- reporting manager
    PanNumber      NVARCHAR(10)      NULL,
    BankName       NVARCHAR(100)     NULL,
    BankAccountNo  NVARCHAR(30)      NULL,
    IfscCode       NVARCHAR(11)      NULL,
    BloodGroup            VARCHAR(3)    NULL CONSTRAINT CK_Employees_BloodGroup CHECK (BloodGroup IN ('A+','A-','B+','B-','AB+','AB-','O+','O-')),
    EmergencyContactName  NVARCHAR(100) NULL,
    EmergencyContactPhone NVARCHAR(20)  NULL,
    IsActive       BIT               NOT NULL CONSTRAINT DF_Employees_IsActive DEFAULT (1),
    CreatedAt      DATETIME2(0)      NOT NULL CONSTRAINT DF_Employees_CreatedAt DEFAULT (SYSUTCDATETIME()),
    UpdatedAt      DATETIME2(0)      NULL,
    CONSTRAINT CK_Employees_Manager CHECK (ManagerId IS NULL OR ManagerId <> EmployeeId)
);
GO
CREATE INDEX IX_Employees_ManagerId ON dbo.Employees(ManagerId);
