CREATE TABLE dbo.Roles
(
    RoleId      INT           NOT NULL CONSTRAINT PK_Roles PRIMARY KEY,
    Name        NVARCHAR(50)  NOT NULL CONSTRAINT UQ_Roles_Name UNIQUE,
    Description NVARCHAR(200) NULL,
    IsSystem    BIT           NOT NULL CONSTRAINT DF_Roles_IsSystem DEFAULT (0)   -- built-in: cannot be renamed / deleted
);
GO
-- Permissions granted to a role (codes are defined in the API: Auth/Permissions.cs).
-- The Admin role (RoleId 1) always has every permission and needs no rows here.
CREATE TABLE dbo.RolePermissions
(
    RoleId     INT          NOT NULL CONSTRAINT FK_RolePermissions_Roles REFERENCES dbo.Roles(RoleId) ON DELETE CASCADE,
    Permission NVARCHAR(50) NOT NULL,
    CONSTRAINT PK_RolePermissions PRIMARY KEY (RoleId, Permission)
);
GO
CREATE TABLE dbo.Users
(
    UserId       INT IDENTITY(1,1) NOT NULL CONSTRAINT PK_Users PRIMARY KEY,
    Username     NVARCHAR(50)      NOT NULL CONSTRAINT UQ_Users_Username UNIQUE,
    PasswordHash NVARCHAR(100)     NOT NULL,          -- BCrypt hash
    RoleId       INT               NOT NULL CONSTRAINT FK_Users_Roles REFERENCES dbo.Roles(RoleId),
    EmployeeId   INT               NULL,
    IsActive     BIT               NOT NULL CONSTRAINT DF_Users_IsActive DEFAULT (1),
    LastLoginAt  DATETIME2(0)      NULL,
    LastSeenAt   DATETIME2(0)      NULL,          -- last chat disconnect (UTC)
    CreatedAt    DATETIME2(0)      NOT NULL CONSTRAINT DF_Users_CreatedAt DEFAULT (SYSUTCDATETIME())
);
GO
-- One login per employee (NULLs allowed for pure admin accounts)
CREATE UNIQUE INDEX UX_Users_EmployeeId ON dbo.Users(EmployeeId) WHERE EmployeeId IS NOT NULL;
GO
-- OAuth 2.0 style refresh tokens (only the SHA-256 hash is stored)
CREATE TABLE dbo.RefreshTokens
(
    RefreshTokenId  BIGINT IDENTITY(1,1) NOT NULL CONSTRAINT PK_RefreshTokens PRIMARY KEY,
    UserId          INT               NOT NULL CONSTRAINT FK_RefreshTokens_Users REFERENCES dbo.Users(UserId) ON DELETE CASCADE,
    TokenHash       CHAR(64)          NOT NULL CONSTRAINT UQ_RefreshTokens_TokenHash UNIQUE,
    ExpiresAt       DATETIME2(0)      NOT NULL,
    CreatedAt       DATETIME2(0)      NOT NULL CONSTRAINT DF_RefreshTokens_CreatedAt DEFAULT (SYSUTCDATETIME()),
    CreatedByIp     NVARCHAR(50)      NULL,
    RevokedAt       DATETIME2(0)      NULL,
    ReplacedByHash  CHAR(64)          NULL
);
GO
CREATE INDEX IX_RefreshTokens_UserId ON dbo.RefreshTokens(UserId);
