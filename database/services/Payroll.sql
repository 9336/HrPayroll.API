    EmployeeId       INT               NOT NULL,
    DocumentType     NVARCHAR(30)      NOT NULL,
    FinancialYear    INT               NULL,       -- Form 16 only: first year of the FY (2025 = FY 2025-26)
    Title            NVARCHAR(200)     NOT NULL,
    IssueDate        DATE              NOT NULL,
    Data             NVARCHAR(MAX)     NOT NULL,
    ReleasedOn       DATETIME2(0)      NOT NULL CONSTRAINT DF_EmployeeDocuments_ReleasedOn DEFAULT (SYSUTCDATETIME()),
    ReleasedByUserId INT               NULL,
    CONSTRAINT CK_EmployeeDocuments_Type CHECK (DocumentType IN ('OfferLetter','RelievingLetter','Form16','PromotionLetter')),
    CONSTRAINT CK_EmployeeDocuments_Data CHECK (ISJSON(Data) = 1)
);
-- One offer / relieving letter per employee and one Form 16 per FY; several promotion letters are allowed.
CREATE UNIQUE INDEX UX_EmployeeDocuments ON dbo.EmployeeDocuments(EmployeeId, DocumentType, FinancialYear)
    WHERE DocumentType <> 'PromotionLetter';
