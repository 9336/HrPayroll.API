-- Salary structure is versioned: a revision = new row with a new EffectiveFrom.
CREATE TABLE dbo.SalaryStructures
(
    SalaryStructureId    INT IDENTITY(1,1) NOT NULL CONSTRAINT PK_SalaryStructures PRIMARY KEY,
    EmployeeId           INT               NOT NULL,
    EffectiveFrom        DATE              NOT NULL,
    BasicPay             DECIMAL(12,2)     NOT NULL,
    Hra                  DECIMAL(12,2)     NOT NULL CONSTRAINT DF_Sal_Hra  DEFAULT (0),
    ConveyanceAllowance  DECIMAL(12,2)     NOT NULL CONSTRAINT DF_Sal_Conv DEFAULT (0),
    MedicalAllowance     DECIMAL(12,2)     NOT NULL CONSTRAINT DF_Sal_Med  DEFAULT (0),
    SpecialAllowance     DECIMAL(12,2)     NOT NULL CONSTRAINT DF_Sal_Spl  DEFAULT (0),
    PfPercent            DECIMAL(5,2)      NOT NULL CONSTRAINT DF_Sal_Pf   DEFAULT (12.00),
    ProfessionalTax      DECIMAL(12,2)     NOT NULL CONSTRAINT DF_Sal_Pt   DEFAULT (200),
    MonthlyTds           DECIMAL(12,2)     NOT NULL CONSTRAINT DF_Sal_Tds  DEFAULT (0),
    GrossMonthly         AS (BasicPay + Hra + ConveyanceAllowance + MedicalAllowance + SpecialAllowance) PERSISTED,
    Remarks              NVARCHAR(300)     NULL,
    CreatedByUserId      INT               NULL,
    CreatedAt            DATETIME2(0)      NOT NULL CONSTRAINT DF_Sal_CreatedAt DEFAULT (SYSUTCDATETIME()),
    CONSTRAINT UQ_SalaryStructures UNIQUE (EmployeeId, EffectiveFrom),
    CONSTRAINT CK_SalaryStructures_Amounts CHECK (BasicPay > 0 AND Hra >= 0 AND ConveyanceAllowance >= 0
                                                  AND MedicalAllowance >= 0 AND SpecialAllowance >= 0
                                                  AND PfPercent BETWEEN 0 AND 100
                                                  AND ProfessionalTax >= 0 AND MonthlyTds >= 0)
);
