-- Check-in / check-out times are office local time.
CREATE TABLE dbo.Attendance
(
    AttendanceId   INT IDENTITY(1,1) NOT NULL CONSTRAINT PK_Attendance PRIMARY KEY,
    EmployeeId     INT               NOT NULL,
    AttendanceDate DATE              NOT NULL,
    CheckInAt      DATETIME2(0)      NOT NULL,
    CheckOutAt     DATETIME2(0)      NULL,
    Notes          NVARCHAR(300)     NULL,
    -- Where the employee checked in / out (attendance area, GPS position, Web or Mobile)
    CheckInLatitude   DECIMAL(9,6)   NULL,
    CheckInLongitude  DECIMAL(9,6)   NULL,
    CheckInAccuracy   INT            NULL,
    CheckInPlace      NVARCHAR(100)  NULL,
    CheckInDistance   INT            NULL,
    CheckInSource     NVARCHAR(10)   NULL,
    CheckOutLatitude  DECIMAL(9,6)   NULL,
    CheckOutLongitude DECIMAL(9,6)   NULL,
    CheckOutAccuracy  INT            NULL,
    CheckOutPlace     NVARCHAR(100)  NULL,
    CheckOutDistance  INT            NULL,
    CheckOutSource    NVARCHAR(10)   NULL,
    CheckInBiometric  BIT            NOT NULL CONSTRAINT DF_Attendance_InBio  DEFAULT (0),   -- Face ID / fingerprint on the registered phone
    CheckOutBiometric BIT            NOT NULL CONSTRAINT DF_Attendance_OutBio DEFAULT (0),
    CheckInFaceScore  DECIMAL(4,3)   NULL,   -- selfie face check (similarity 0-1)
    CheckOutFaceScore DECIMAL(4,3)   NULL,
    CONSTRAINT UQ_Attendance UNIQUE (EmployeeId, AttendanceDate),
    CONSTRAINT CK_Attendance_Times CHECK (CheckOutAt IS NULL OR CheckOutAt >= CheckInAt)
);
GO
-- Attendance areas (geofences): employees must be inside one that applies to them to check in / out.
CREATE TABLE dbo.AttendanceLocations
(
    LocationId      INT IDENTITY(1,1) NOT NULL CONSTRAINT PK_AttendanceLocations PRIMARY KEY,
    Name            NVARCHAR(100)  NOT NULL CONSTRAINT UQ_AttendanceLocations_Name UNIQUE,
    Address         NVARCHAR(300)  NULL,
    Latitude        DECIMAL(9,6)   NOT NULL CONSTRAINT CK_AttendanceLocations_Lat CHECK (Latitude BETWEEN -90 AND 90),
    Longitude       DECIMAL(9,6)   NOT NULL CONSTRAINT CK_AttendanceLocations_Lng CHECK (Longitude BETWEEN -180 AND 180),
    RadiusMeters    INT            NOT NULL CONSTRAINT CK_AttendanceLocations_Radius CHECK (RadiusMeters BETWEEN 20 AND 5000),
    AllEmployees    BIT            NOT NULL CONSTRAINT DF_AttendanceLocations_All DEFAULT (1),
    IsActive        BIT            NOT NULL CONSTRAINT DF_AttendanceLocations_Active DEFAULT (1),
    CreatedByUserId INT            NOT NULL,
    CreatedAt       DATETIME2(0)   NOT NULL CONSTRAINT DF_AttendanceLocations_Created DEFAULT (SYSUTCDATETIME()),
    UpdatedAt       DATETIME2(0)   NULL
);
GO
