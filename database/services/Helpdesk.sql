        ApprovedAt         DATETIME2(0)      NULL,   -- UTC
        ApprovalRemarks    NVARCHAR(1000)    NULL,
        AssignedToUserId   INT               NULL,
        ResolutionNotes    NVARCHAR(1000)    NULL,
        CompletedAt        DATETIME2(0)      NULL,   -- UTC
        CreatedAt          DATETIME2(0)      NOT NULL CONSTRAINT DF_ItRequests_CreatedAt DEFAULT (SYSUTCDATETIME()),
        UpdatedAt          DATETIME2(0)      NULL
