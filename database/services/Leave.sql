CREATE VIEW dbo.vw_EmployeeLeaveSummary
AS
SELECT  e.EmployeeId,
        e.EmployeeCode,
        e.FirstName + N' ' + e.LastName AS EmployeeName,
        lb.[Year],
        lt.Code  AS LeaveCode,
        lt.Name  AS LeaveName,
        lb.Allocated,
        lb.CarryForwarded,
        lb.Used,
        lb.Available
FROM    dbo.LeaveBalances lb
JOIN    dbo.Employees     e  ON e.EmployeeId  = lb.EmployeeId
JOIN    dbo.LeaveTypes    lt ON lt.LeaveTypeId = lb.LeaveTypeId;
GO
