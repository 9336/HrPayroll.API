/* Year-opening job: allocates annual leave quota to every active employee
   and carries forward unused balance (capped by MaxCarryForward).
   Employees joining mid-year get a pro-rated quota (rounded to 0.5).
   Safe to re-run: existing rows are not touched. */
CREATE PROCEDURE dbo.usp_AllocateYearlyLeaves
    @Year       INT,
    @EmployeeId INT = NULL      -- NULL = all active employees
AS
BEGIN
    SET NOCOUNT ON;

    INSERT INTO dbo.LeaveBalances (EmployeeId, LeaveTypeId, [Year], Allocated, CarryForwarded, Used)
    SELECT  e.EmployeeId,
            lt.LeaveTypeId,
            @Year,
            -- pro-rata for joiners of this year: quota * remaining months / 12, rounded to 0.5
            CASE WHEN YEAR(e.DateOfJoining) = @Year AND lt.IsProRated = 1
                 THEN ROUND(lt.AnnualQuota * (13 - MONTH(e.DateOfJoining)) / 12.0 * 2, 0) / 2
                 ELSE lt.AnnualQuota END,
            CASE WHEN lt.AllowCarryForward = 1
                 THEN ISNULL(CASE WHEN prev.Available > lt.MaxCarryForward THEN lt.MaxCarryForward
                                  WHEN prev.Available < 0 THEN 0
                                  ELSE prev.Available END, 0)
                 ELSE 0 END,
            0
    FROM    dbo.Employees  e
    CROSS JOIN dbo.LeaveTypes lt
    LEFT JOIN dbo.LeaveBalances prev
           ON prev.EmployeeId = e.EmployeeId AND prev.LeaveTypeId = lt.LeaveTypeId AND prev.[Year] = @Year - 1
    WHERE   e.IsActive = 1
      AND   lt.IsActive = 1
      AND   lt.IsBalanceTracked = 1
      AND   (lt.ApplicableGender IS NULL OR lt.ApplicableGender = e.Gender)
      AND   YEAR(e.DateOfJoining) <= @Year
      AND   (@EmployeeId IS NULL OR e.EmployeeId = @EmployeeId)
      AND   NOT EXISTS (SELECT 1 FROM dbo.LeaveBalances x
                        WHERE x.EmployeeId = e.EmployeeId AND x.LeaveTypeId = lt.LeaveTypeId AND x.[Year] = @Year);

    SELECT @@ROWCOUNT AS RowsAllocated;
END
GO
CREATE PROCEDURE dbo.usp_GetEmployeeLeaveHistory
    @EmployeeId INT,
    @Year       INT = NULL
AS
BEGIN
    SET NOCOUNT ON;
    SELECT  lr.LeaveRequestId, lt.Code, lt.Name, lr.FromDate, lr.ToDate, lr.IsHalfDay,
            lr.TotalDays, lr.Reason, lr.Status, lr.AppliedOn, lr.ActionedOn, lr.AdminRemarks
    FROM    dbo.LeaveRequests lr
    JOIN    dbo.LeaveTypes lt ON lt.LeaveTypeId = lr.LeaveTypeId
    WHERE   lr.EmployeeId = @EmployeeId
      AND   (@Year IS NULL OR YEAR(lr.FromDate) = @Year)
    ORDER BY lr.FromDate DESC;
END
